	private final String displayName;
	private final int[] gameObjectIds;
	private final int raftCapacity;
	private final int skiffCapacity;
	private final int sloopCapacity;

	CargoHoldTier(
		String displayName,
		int[] gameObjectIds,
		int raftCapacity,
		int skiffCapacity,
		int sloopCapacity)
	{
		this.displayName = displayName;
		this.gameObjectIds = gameObjectIds;
		this.raftCapacity = raftCapacity;
		this.skiffCapacity = skiffCapacity;
		this.sloopCapacity = sloopCapacity;
	}

	public String getDisplayName()
	{
		return displayName;
	}

	public static CargoHoldTier fromGameObjectId(int objectId)
	{
		for (CargoHoldTier tier : values())
		{
			for (int candidate : tier.gameObjectIds)
			{
				if (candidate == objectId)
				{
					return tier;
				}
			}
		}

		return null;
	}

	public int getCapacity(ShipSize shipSize)
	{
		if (shipSize == null || shipSize == ShipSize.AUTO)
		{
			return -1;
		}

		switch (shipSize)
		{
			case RAFT:
				return raftCapacity;
			case SKIFF:
				return skiffCapacity;
			case SLOOP:
				return sloopCapacity;
			default:
				return -1;
		}
	}
